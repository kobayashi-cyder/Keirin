#!/usr/bin/env python3
"""Seven-market probability projection from a joint ordered top-three distribution.

Research-only. No scraping, training, purchases, or notifications.
The caller MUST supply pre-race probabilities from a separately calibrated model.
"""
from __future__ import annotations

import argparse
import itertools
import json
import math
from collections import Counter, defaultdict
from datetime import datetime, timedelta, timezone
from pathlib import Path

MARKETS = (
    "3rentan", "3renpuku", "2shatan", "2shafuku",
    "2wakutan", "2wakufuku", "wide",
)
FRAME_BY_SIZE = {
    7: (1, 2, 3, 4, 5, 6, 6),
    8: (1, 2, 3, 4, 5, 5, 6, 6),
    9: (1, 2, 3, 4, 4, 5, 5, 6, 6),
}


def finite_number(value, *, positive=False):
    if type(value) not in (int, float) or not math.isfinite(value):
        raise ValueError("expected finite numeric value")
    if positive and value <= 0:
        raise ValueError("expected positive value")
    return float(value)


def validate_cars(cars):
    if (not isinstance(cars, list) or len(cars) not in FRAME_BY_SIZE or
            any(type(c) is not int for c in cars) or
            sorted(cars) != list(range(1, len(cars) + 1))):
        raise ValueError("cars must be precisely 1..7, 1..8, or 1..9")
    return tuple(cars)


def _key(*numbers, unordered=False):
    if unordered:
        numbers = tuple(sorted(numbers))
    return "-".join(str(i) for i in numbers)


def validate_top3(cars, raw):
    """Reject unnormalised, duplicated, or impossible ordered outcomes."""
    cars = validate_cars(cars)
    if not isinstance(raw, dict) or not raw:
        raise ValueError("missing joint top-three probabilities")
    result = {}
    for key, value in raw.items():
        if not isinstance(key, str):
            raise ValueError("top-three outcome must be a string")
        parts = key.split("-")
        if len(parts) != 3 or not all(x.isascii() and x.isdigit() for x in parts):
            raise ValueError("invalid top-three outcome")
        order = tuple(int(x) for x in parts)
        if len(set(order)) != 3 or any(x not in cars for x in order):
            raise ValueError("unknown or repeated car in top-three outcome")
        if _key(*order) != key:
            raise ValueError("noncanonical top-three outcome")
        p = finite_number(value)
        if p < 0:
            raise ValueError("negative probability")
        result[order] = p
    if not math.isclose(math.fsum(result.values()), 1.0, rel_tol=0, abs_tol=1e-8):
        raise ValueError("joint top-three probabilities must sum to 1")
    return result


def plackett_luce_demo(cars, strengths):
    """Illustrative coherent distribution; NOT a calibrated racing predictor."""
    cars = validate_cars(cars)
    if not isinstance(strengths, dict) or set(strengths) != set(cars):
        raise ValueError("strengths must be supplied for all cars")
    weights = {c: finite_number(strengths[c], positive=True) for c in cars}
    total = math.fsum(weights.values())
    output = {}
    for a, b, c in itertools.permutations(cars, 3):
        p = (weights[a] / total *
             weights[b] / (total - weights[a]) *
             weights[c] / (total - weights[a] - weights[b]))
        output[_key(a, b, c)] = p
    return validate_top3(list(cars), output)


def from_joint_finish_time_samples(cars, samples):
    """Each sample is a jointly simulated finish-time vector, in car order.

    Dependence between riders must be generated by the caller. Ties cannot
    be silently broken; disqualification/refund is outside this model.
    """
    cars = validate_cars(cars)
    if not isinstance(samples, list) or not samples:
        raise ValueError("finish-time samples must be a nonempty list")
    counts = Counter()
    for row in samples:
        if not isinstance(row, list) or len(row) != len(cars):
            raise ValueError("sample must include one time for each car")
        times = tuple(finite_number(x, positive=True) for x in row)
        if len(set(times)) != len(times):
            raise ValueError("tied finish times require separate rules")
        order = tuple(c for _, c in sorted(zip(times, cars)))[:3]
        counts[order] += 1
    n = len(samples)
    return {order: count / n for order, count in counts.items()}


def project_all_markets(cars, distribution):
    """Compute coherent probabilities for all seven ordinary bet types.

    Same-frame pairs (such as 4-4 in a nine-car race) are deliberately valid.
    A market not offered by the operator must be excluded by the odds input.
    """
    cars = validate_cars(cars)
    if isinstance(distribution, dict) and all(isinstance(k, str) for k in distribution):
        distribution = validate_top3(list(cars), distribution)
    else:
        distribution = validate_top3(list(cars), {
            _key(*k): v for k, v in distribution.items()
        })
    frame = {car: FRAME_BY_SIZE[len(cars)][car - 1] for car in cars}
    out = {market: defaultdict(float) for market in MARKETS}
    for (a, b, c), p in distribution.items():
        if p == 0:
            continue
        fa, fb = frame[a], frame[b]
        out["3rentan"][_key(a, b, c)] += p
        out["3renpuku"][_key(a, b, c, unordered=True)] += p
        out["2shatan"][_key(a, b)] += p
        out["2shafuku"][_key(a, b, unordered=True)] += p
        out["2wakutan"][_key(fa, fb)] += p
        out["2wakufuku"][_key(fa, fb, unordered=True)] += p
        for x, y in itertools.combinations((a, b, c), 2):
            out["wide"][_key(x, y, unordered=True)] += p
    return {market: dict(sorted(table.items())) for market, table in out.items()}


def evaluate_offered_odds(projected, offered, *, threshold=1.30, stress=0.75):
    """Use only supplied odds. For wide/range quotes use the lower bound."""
    threshold = finite_number(threshold, positive=True)
    stress = finite_number(stress, positive=True)
    if stress > 1:
        raise ValueError("stress must be at most 1")
    if not isinstance(offered, dict):
        raise ValueError("offered odds must be a market mapping")
    result = []
    for market, table in offered.items():
        if market not in MARKETS or not isinstance(table, dict):
            raise ValueError(f"unrecognised market or odds format: {market}")
        for combo, quote in table.items():
            if combo not in projected[market]:
                raise ValueError(f"unknown or noncanonical ticket: {market}/{combo}")
            if isinstance(quote, dict) and set(quote) == {"min", "max"}:
                price = finite_number(quote["min"], positive=True)
                upper = finite_number(quote["max"], positive=True)
                if price > upper:
                    raise ValueError("inverted odds range")
            else:
                price = finite_number(quote, positive=True)
                upper = price
            if price < 1:
                raise ValueError("odds must be >= 1")
            prob = projected[market][combo]
            raw_ev = prob * price
            stressed_ev = raw_ev * stress
            if stressed_ev + 1e-12 >= threshold:
                result.append({
                    "market": market, "combo": combo,
                    "probability": round(prob, 10),
                    "odds_used": price, "odds_upper": upper,
                    "expected_return": round(raw_ev, 6),
                    "stressed_return": round(stressed_ev, 6),
                    "stressed_profit_percent": round((stressed_ev - 1) * 100, 4),
                })
    return sorted(result, key=lambda row: (-row["stressed_return"], row["market"], row["combo"]))


def _aware(iso_value):
    if not isinstance(iso_value, str):
        raise ValueError("missing timestamp")
    time = datetime.fromisoformat(iso_value)
    if time.tzinfo is None or time.utcoffset() is None:
        raise ValueError("timestamp must include a UTC offset")
    return time.astimezone(timezone.utc)


def shadow_report(payload, *, now=None, threshold=1.30, stress=0.75, top=20):
    """Analyze only: cannot authorize a paper bet or trigger a live alert."""
    if not isinstance(payload, dict) or not isinstance(payload.get("race_id"), str):
        raise ValueError("race_id is required")
    cars = payload.get("cars")
    validate_cars(cars)
    model = payload.get("probability_input")
    if not isinstance(model, dict):
        raise ValueError("probability_input is required")
    if model.get("type") == "top3_probabilities":
        dist = validate_top3(cars, model.get("values"))
    elif model.get("type") == "joint_finish_time_samples":
        dist = from_joint_finish_time_samples(cars, model.get("samples"))
    else:
        raise ValueError("only joint top3 probabilities or joint finish-time samples are supported")
    source_url = payload.get("odds_source_url")
    if not isinstance(source_url, str) or not source_url.startswith("https://"):
        raise ValueError("odds_source_url must be an HTTPS link")
    observed = _aware(payload.get("odds_observed_at"))
    deadline = _aware(payload.get("deadline_at"))
    if observed >= deadline:
        raise ValueError("odds observation must precede deadline")
    now = now or datetime.now(timezone.utc)
    if now.tzinfo is None or now.utcoffset() is None:
        raise ValueError("current time must be timezone-aware")
    now = now.astimezone(timezone.utc)
    if now >= deadline:
        freshness = "closed_or_historical"
    elif observed > now:
        freshness = "future_observation"
    elif now - observed > timedelta(minutes=10):
        freshness = "stale_odds"
    elif deadline - now < timedelta(minutes=10):
        freshness = "too_close_to_deadline"
    else:
        freshness = "recent_preclose_observation"
    prices = payload.get("offered_odds")
    projection = project_all_markets(cars, dist)
    candidates = evaluate_offered_odds(projection, prices, threshold=threshold, stress=stress)
    return {
        "status": "SHADOW_ONLY_UNVALIDATED", "alert_allowed": False,
        "race_id": payload["race_id"], "probability_input_type": model["type"],
        "odds_source_url": source_url, "odds_observed_at": payload["odds_observed_at"],
        "deadline_at": payload["deadline_at"], "freshness": freshness,
        "threshold_return": threshold, "stress_factor": stress,
        "joint_top3_outcomes": len(dist),
        "market_types_priced": sorted(prices),
        "qualifying_count": len(candidates), "candidates": candidates[:top],
        "warning": "No validated prediction model or authorized live feed; no betting/Discord.",
    }


def demo():
    cars = list(range(1, 8))
    dist = plackett_luce_demo(cars, {1: 5, 2: 4, 3: 3, 4: 2, 5: 2, 6: 1, 7: 1})
    projected = project_all_markets(cars, dist)
    odds = {
        "3rentan": {"1-2-3": 55.0},
        "3renpuku": {"1-2-3": 10.0},
        "2shatan": {"1-2": 15.0},
        "2shafuku": {"1-2": 7.0},
        "2wakutan": {"6-6": 120.0},
        "2wakufuku": {"6-6": 120.0},
        "wide": {"1-2": {"min": 5.0, "max": 6.0}},
    }
    return {
        "status": "SYNTHETIC_DEMO_ONLY", "alert_allowed": False,
        "cars": cars, "top3_outcomes": len(dist),
        "projection_probability_sums": {
            k: round(math.fsum(v.values()), 8) for k, v in projected.items()
        },
        "candidates": evaluate_offered_odds(projected, odds),
        "warning": "The strengths and odds are invented. Not a race prediction.",
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--demo", action="store_true")
    group.add_argument("--input", type=Path, help="JSON with independently generated probabilities and market odds")
    parser.add_argument("--output", type=Path, help="save research report as JSON")
    parser.add_argument("--top", type=int, default=20)
    args = parser.parse_args()
    if args.top < 1:
        parser.error("--top must be positive")
    result = demo() if args.demo else shadow_report(
        json.loads(args.input.read_text(encoding="utf-8")), top=args.top
    )
    serialized = json.dumps(result, ensure_ascii=False, indent=2) + "\n"
    if args.output:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(serialized, encoding="utf-8")
    print(serialized, end="")


if __name__ == "__main__":
    main()
