#!/usr/bin/env python3
"""Import permissioned, *actually observed before close* rider features from CSV.

No website access, credentials, implied rights, predictions, or bets.
Only pre-close observations already in a user-supplied CSV are admitted.
Append-only local archive; existing race IDs are never overwritten.
"""
from __future__ import annotations

import argparse
import csv
import os
import sys
import tempfile
from collections import defaultdict
from datetime import datetime
from pathlib import Path
from zoneinfo import ZoneInfo

from pre_race_readiness import COLUMNS, _valid_row, time_with_zone

JST = ZoneInfo("Asia/Tokyo")
EXTRA = ("ingested_at_jst",)
OUTPUT_COLUMNS = COLUMNS + EXTRA


def csv_rows(path):
    with path.open(encoding="utf-8-sig", newline="") as fh:
        reader = csv.DictReader(fh)
        if not reader.fieldnames:
            raise ValueError("input CSV has no header")
        if len(reader.fieldnames) != len(set(reader.fieldnames)):
            raise ValueError("duplicate CSV header column")
        missing = set(COLUMNS) - set(reader.fieldnames)
        if missing:
            raise ValueError("missing columns: " + ", ".join(sorted(missing)))
        if "ingested_at_jst" in reader.fieldnames:
            raise ValueError("ingested_at_jst is generated by this program")
        rows = list(reader)
    if not rows:
        raise ValueError("empty input; enter real pre-race data, do not invent values")
    return rows


def validate_rows(rows, *, now):
    if now.tzinfo is None or now.utcoffset() is None:
        raise ValueError("now must contain a timezone")
    by_race = defaultdict(list)
    for row in rows:
        if not isinstance(row, dict):
            raise ValueError("invalid row")
        rid = row.get("race_id", "")
        if not rid or not isinstance(rid, str):
            raise ValueError("missing race_id")
        by_race[rid].append(row)

    for rid, race_rows in by_race.items():
        if len(race_rows) not in (7, 8, 9):
            raise ValueError(f"{rid}: expected exactly 7, 8 or 9 rider rows")
        cars, meta, line_positions = set(), set(), defaultdict(set)
        for row in race_rows:
            try:
                car_no, observed, deadline, start = _valid_row(row)
            except (ValueError, TypeError, KeyError, OverflowError) as exc:
                raise ValueError(f"{rid}: {exc}") from exc
            if car_no in cars:
                raise ValueError(f"{rid}: duplicate rider number {car_no}")
            cars.add(car_no)
            if observed > now:
                raise ValueError(f"{rid}: observation time is in the future")
            if now >= deadline:
                raise ValueError(f"{rid}: race already closed; retrospective import denied")
            meta.add((deadline, start, row["race_date"]))
            position = int(float(row["line_position"]))
            line_id = row["line_id"]
            if position in line_positions[line_id]:
                raise ValueError(f"{rid}: duplicate line position")
            line_positions[line_id].add(position)
            a = float(row["recent_win_rate"])
            b = float(row["recent_top2_rate"])
            c = float(row["recent_top3_rate"])
            if not a <= b <= c:
                raise ValueError(f"{rid}: rates must satisfy win <= top2 <= top3")
        if cars != set(range(1, len(race_rows) + 1)):
            raise ValueError(f"{rid}: rider numbers must be consecutive starting at 1")
        if len(meta) != 1:
            raise ValueError(f"{rid}: mixed deadline, start time or race date")
    return by_race


def intake(input_path, output_path, *, now=None):
    now = now or datetime.now(JST)
    now = now.astimezone(JST)
    input_path, output_path = Path(input_path), Path(output_path)
    source = csv_rows(input_path)
    incoming = validate_rows(source, now=now)

    previous = []
    if output_path.exists():
        with output_path.open(encoding="utf-8-sig", newline="") as fh:
            reader = csv.DictReader(fh)
            if reader.fieldnames != list(OUTPUT_COLUMNS):
                raise ValueError("existing archive has incompatible header")
            previous = list(reader)
        existing_ids = {row["race_id"] for row in previous}
        collided = existing_ids & set(incoming)
        if collided:
            raise ValueError("already archived race_id(s), no overwrite: " +
                             ", ".join(sorted(collided)))

    stamp = now.isoformat()
    new_rows = [
        {k: row[k] for k in COLUMNS} | {"ingested_at_jst": stamp}
        for race_rows in incoming.values() for row in race_rows
    ]
    output_path.parent.mkdir(parents=True, exist_ok=True)

    # Atomic replacement: a failed validation cannot partially append a race.
    temp_path = None
    try:
        with tempfile.NamedTemporaryFile(
            mode="w", newline="", encoding="utf-8", suffix=".tmp",
            prefix="pre_race_", dir=output_path.parent, delete=False,
        ) as fh:
            temp_path = Path(fh.name)
            writer = csv.DictWriter(fh, fieldnames=OUTPUT_COLUMNS)
            writer.writeheader()
            writer.writerows(previous)
            writer.writerows(new_rows)
        os.replace(temp_path, output_path)
    finally:
        if temp_path is not None and temp_path.exists():
            temp_path.unlink()
    return {"status": "ARCHIVED_PRE_RACE_FEATURES_ONLY",
            "races_added": len(incoming), "rider_rows_added": len(new_rows),
            "archive_path": str(output_path),
            "prediction_allowed": False, "alert_allowed": False}


def create_template(path):
    path = Path(path)
    if path.exists():
        raise ValueError("template exists; refusing to overwrite it")
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8", newline="") as fh:
        csv.DictWriter(fh, fieldnames=COLUMNS).writeheader()
    return path


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--template", type=Path, help="create header-only template")
    group.add_argument("--input", type=Path, help="CSV with 7/8/9 real rider entries per race")
    parser.add_argument("--output", type=Path,
                        default=Path("local_data/pre_race_features.csv"))
    args = parser.parse_args()
    try:
        if args.template:
            print(f"Template created: {create_template(args.template)}")
        else:
            import json
            print(json.dumps(intake(args.input, args.output), ensure_ascii=False, indent=2))
    except (ValueError, OSError, csv.Error) as exc:
        print(f"IMPORT REJECTED: {exc}", file=sys.stderr)
        return 2
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
